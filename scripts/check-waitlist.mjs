import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const browser = await chromium.launch();
const page = await browser.newPage({viewport:{width:1440,height:1000}});
await page.goto('http://localhost:8091/waitlist.html');
await page.screenshot({path:'output/waitlist/desktop.png',fullPage:true});
await page.setViewportSize({width:390,height:844});
assert(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth));
await page.screenshot({path:'output/waitlist/mobile.png',fullPage:true});
for(const [name,value] of Object.entries({name:'Waitlist Test',company:'Example',email:'waitlist-test@example.com',problem:'Test organizational search'})) await page.locator(`[name=${name}]`).fill(value);
for(const [name,value] of Object.entries({company_size:'11–50',timeline:'Just exploring',pilot:'Maybe'})) await page.locator(`[name=${name}]`).selectOption(value);
await page.locator('[name=consent]').check();
await page.locator('button[type=submit]').click();
assert.match(await page.locator('#waitlist-status').textContent(),/select at least one/);
await page.locator('[name=interests]').first().check();
await page.route('**/functions/v1/company-waitlist', route=>route.fulfill({status:503,body:'unavailable'}));
await page.locator('button[type=submit]').click();
await page.waitForFunction(()=>document.querySelector('#waitlist-status').textContent.includes('couldn’t'));
assert.equal(await page.locator('[name=email]').inputValue(),'waitlist-test@example.com');
await page.unroute('**/functions/v1/company-waitlist');
await page.route('**/functions/v1/company-waitlist', async route=>{
 const {submission}=route.request().postDataJSON();
 assert.equal(submission.consent,true);assert.equal(submission.interests.length,1);
 await route.fulfill({status:204});
});
await page.locator('button[type=submit]').click();
await page.waitForFunction(()=>document.querySelector('#waitlist-status').textContent.includes('Thank you'));
assert(await page.locator('button[type=submit]').isDisabled());
await browser.close();
console.log('Waitlist: mobile overflow, required interests, retry with preserved answers, payload and success state passed (mocked transport).');
